"""Animate the shared AV bus stopping, opening its doors and deploying its ramp.

Open an AV_Bus_Master.blend generated by build_av_bus.py, then Run Script in
Blender's Text Editor. Or run in the background:
    blender --background AV_Bus_Master.blend --python animate_stop_ramp.py \
      -- --save AV_Bus_Stop_Ramp.blend

The bus approaches in frames 1-36, remains still while boarding in 36-156,
and departs during 156-192. The canopy remains retracted throughout.
"""

import argparse
from pathlib import Path
import runpy
import sys

import bpy


def animate_scene(with_canopy=False, save_path=None):
    api = runpy.run_path(str(Path(__file__).with_name("build_av_bus.py")),
                         run_name="av_bus_api")
    root = bpy.data.objects.get("AV_BUS_ROOT")
    if root is None or root.name not in bpy.context.scene.objects:
        raise RuntimeError("Open or append the master AV bus before running this scene script")
    # Separate scene files protect each teammate's version of the animation.
    animated = [obj.name for obj in [root, *api["_asset_descendants"](root)]
                if obj.animation_data and obj.animation_data.action]
    if animated:
        raise RuntimeError("This bus already has keyframes. Start from a fresh master: " +
                           ", ".join(animated[:3]))

    if bpy.context.scene.camera is None:
        api["add_preview_stage"](root)
    scene = bpy.context.scene
    scene.name = ("AV Bus - Stop + Ramp + Canopy" if with_canopy
                  else "AV Bus - Stop + Ramp")
    scene.frame_start = 1
    scene.frame_end = 192
    scene.render.fps = 24
    scene.render.engine = "BLENDER_EEVEE"
    if scene.camera and scene.camera.data.type == 'ORTHO':
        scene.camera.data.ortho_scale = 10.3

    # Only the parent root moves; the bus is stationary through the full dwell.
    for frame, x in ((1, -1.20), (36, 0.0), (156, 0.0), (192, 1.20)):
        root.location.x = x
        root.keyframe_insert(data_path="location", frame=frame)
    for frame, angle in ((1, 0.0), (36, 2.60),
                         (156, 2.60), (192, 5.20)):
        api["keyframe_wheel_rotation"](root, frame, angle)

    api["set_doors"](root, 0.0, frame=36)
    api["set_ramp"](root, 0.0, frame=36)
    api["set_canopy"](root, 0.0, frame=36)

    # Doors first; ramp then slides straight out and tips down to the curb.
    api["set_doors"](root, 1.0, frame=54)
    api["set_ramp"](root, 0.0, frame=55)
    api["set_ramp"](root, 0.70, frame=72)
    api["set_ramp"](root, 1.0, frame=84)
    api["set_ramp"](root, 1.0, frame=112)
    api["set_ramp"](root, 0.70, frame=124)
    api["set_ramp"](root, 0.0, frame=140)
    api["set_doors"](root, 1.0, frame=140)
    api["set_doors"](root, 0.0, frame=152)

    if with_canopy:
        # Weather shelter operates only at the stop and retracts before motion.
        api["set_canopy"](root, 1.0, frame=62)
        api["set_canopy"](root, 1.0, frame=140)
        api["set_canopy"](root, 0.0, frame=155)
    else:
        api["set_canopy"](root, 0.0, frame=192)

    root["scene_variant"] = "ramp_and_canopy" if with_canopy else "ramp_only"
    root["stop_frame"] = 36
    root["departure_frame"] = 156
    scene.frame_set(1)
    if save_path:
        bpy.ops.wm.save_as_mainfile(filepath=str(Path(save_path).resolve()))
    print(f"Ready: {scene.name}; frames 1-192 at 24 fps", flush=True)
    return root


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument("--save", help="Optional output .blend path")
    args = parser.parse_args(argv)
    animate_scene(with_canopy=False, save_path=args.save)


if __name__ == "__main__":
    main()
